/// A 5x7 dot-matrix font, like an LED sign. Glyphs are drawn row by row ("#" = lit). Most are 5 dots
/// wide; punctuation is narrower so text keeps an even rhythm. Lowercase is drawn as uppercase and
/// accents are dropped, which is how real LED signs behave.
enum PixelFont {
    static let rows = 7

    struct Glyph {
        let width: Int
        /// Lit dots as (column, row).
        let dots: [(Int, Int)]
    }

    static func glyph(_ c: Character) -> Glyph { table[c] ?? table[normalize(c)] ?? table["?"]! }

    /// True when every character can be drawn without falling back to "?".
    static func canDraw(_ s: String) -> Bool {
        s.allSatisfy { table[$0] != nil || table[normalize($0)] != nil }
    }

    /// Width in dots, including one dot of space between glyphs (none after the last).
    static func width(_ s: String) -> Int {
        let ws = s.map { glyph($0).width }
        return ws.reduce(0, +) + max(0, ws.count - 1)
    }

    private static func normalize(_ c: Character) -> Character {
        let folded = String(c).folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "en_US")).uppercased()
        return folded.first ?? c
    }

    private static let table: [Character: Glyph] = {
        var t: [Character: Glyph] = [:]
        for (c, rows) in source {
            let width = rows.map(\.count).max() ?? 0
            var dots: [(Int, Int)] = []
            for (y, row) in rows.enumerated() {
                for (x, ch) in row.enumerated() where ch == "#" { dots.append((x, y)) }
            }
            t[c] = Glyph(width: width, dots: dots)
        }
        return t
    }()

