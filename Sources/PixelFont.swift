/// Glyph masks for the Matrix rain, one strip of equal-size cells.
struct GlyphAtlas {
    let cellW: Int, cellH: Int, count: Int
    /// 0...255 coverage, `cellW * count` wide and `cellH` tall.
    let mask: [UInt8]

    /// Built from the dot font, for platforms without a system font renderer (and for tests).
    static func dotFont(height: Int) -> GlyphAtlas {
        let ch = max(6, Int((Double(height) / 3).rounded())), cw = max(4, Int((Double(ch) * 0.68).rounded()))
        let glyphs = Array("0123456789ｱｲｳｴｵｶｷｸｹｺ")
        let aw = cw * glyphs.count
        var m = [UInt8](repeating: 0, count: aw * ch)
        for (i, c) in glyphs.enumerated() {
            let g = PixelFont.glyph(c)
            let sx = Double(cw) / 6, sy = Double(ch) / 8
            for (dx, dy) in g.dots {
                let x0 = Int((Double(dx) + 0.5) * sx), y0 = Int((Double(dy) + 0.5) * sy)
                let x1 = max(x0 + 1, Int((Double(dx) + 1.5) * sx)), y1 = max(y0 + 1, Int((Double(dy) + 1.5) * sy))
                for y in y0..<min(ch, y1) { for x in x0..<min(cw, x1) { m[y * aw + i * cw + x] = 255 } }
            }
        }
        return GlyphAtlas(cellW: cw, cellH: ch, count: glyphs.count, mask: m)
    }
}
