#!/usr/bin/env python3
"""Builds app .strings files (Resources/lproj) and the website's docs/i18n.json from i18n/*.py.

  python3 tools/gen_i18n.py          # generate
  python3 tools/gen_i18n.py --check  # also list user-facing strings in the code that have no translation
"""
import json, pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "i18n"))
from app_strings import APP
try:
    from site_strings import SITE
except ImportError:
    SITE = []

LANGS = ["es", "pt", "fr", "hi", "zh"]
FOLDER = {"es": "es", "pt": "pt", "fr": "fr", "hi": "hi", "zh": "zh-Hans"}

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

for i, lang in enumerate(LANGS, start=1):
    d = root / "Resources" / "lproj" / f"{FOLDER[lang]}.lproj"
    d.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/gen_i18n.py from i18n/app_strings.py. Do not edit. */"]
    for row in APP:
        assert len(row) == 6, row
        lines.append(f'"{esc(row[0])}" = "{esc(row[i])}";')
    (d / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")

# Website: {lang: {english: translated}}
site = {lang: {} for lang in LANGS}
# The site also shows effect names and a few app strings, so include those too (site wording wins on overlap).
for row in list(APP) + list(SITE):
    assert len(row) == 6, row
    for i, lang in enumerate(LANGS, start=1):
        site[lang][row[0]] = row[i]
if (root / "docs").is_dir():   # the public app repo has no website
    (root / "docs" / "i18n.json").write_text(json.dumps(site, ensure_ascii=False, indent=0), encoding="utf-8")
print(f"app: {len(APP)} strings x {len(LANGS)} languages; site: {len(SITE)} strings")

if "--check" in sys.argv:
    have = {r[0] for r in APP}
    pats = [r'Text\(loc\("((?:[^"\\]|\\.)*)"', r'Text\("((?:[^"\\]|\\.)*)"', r'Button\("((?:[^"\\]|\\.)*)"', r'Label\("((?:[^"\\]|\\.)*)"',
            r'Toggle\("((?:[^"\\]|\\.)*)"', r'TextField\("((?:[^"\\]|\\.)*)"', r'NSLocalizedString\("((?:[^"\\]|\\.)*)"',
            r'loc\("((?:[^"\\]|\\.)*)"', r'fmt\("((?:[^"\\]|\\.)*)"', r'slider\("((?:[^"\\]|\\.)*)"',
            r'title: "((?:[^"\\]|\\.)*)"', r'hint: "((?:[^"\\]|\\.)*)"', r'detail: "((?:[^"\\]|\\.)*)"',
            r'L\("((?:[^"\\]|\\.)*)"\)', r'\? "((?:[^"\\]|\\.)*)" :', r': "((?:[^"\\]|\\.)*)"\)', r'case \.\w+: "((?:[^"\\]|\\.)*)"',
            r'\("([A-Z][A-Za-z ]+)", "[0-9A-F]{6}"\)']
    found = set()
    # The renderer files hold text drawn on the bar itself (kept in English on purpose), not UI strings.
    skip = {"PricingTable.swift", "Effects.swift", "SynthKnob.swift", "Canvas.swift", "PixelFont.swift", "EffectCore.swift",
            "Scene.swift", "LiveInfoSource.swift", "Drops.swift"}
    for f in (root / "Sources").glob("*.swift"):
        if f.name in skip or f.name.startswith("Library"): continue
        src = f.read_text()
        for p in pats:
            for m in re.finditer(p, src): found.add(m.group(1))
    ignore = {"", "Revive the Touchbar", "xmark", "clock", "lock.fill", "plus", "checkmark", "circle"}
    missing = sorted(s for s in found if s not in have and s not in ignore and not s.startswith(("com.", "%.", "ReviveTheTouchbar")))
    print("\nStrings in code with no translation (review; some are not user-facing):")
    for s in missing: print("  -", s)
